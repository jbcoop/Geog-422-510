CREATE TABLE tanks (
  the_geom GEOMETRY(POINT, 4326),
  OBJECTID INTEGER,
  UNDERGROUND_TANK_SYSTEM_ID INTEGER,
  UST_ID VARCHAR(255),
  FACILITY_NAME VARCHAR(255),
  APPROXIMATE_LOCATION_OF_TANK VARCHAR(255),
  FACILITY_ADDRESS VARCHAR(255),
  STREET_NAME VARCHAR(255),
  ORDINANCE_FOR_ROW VARCHAR(255),
  SOURCE VARCHAR(255),
  HYPERLINK_TO_COUNCIL_MINUTES VARCHAR(255),
  DATE DATE,
  LOCATED_IN_RECHARGE_ZONE VARCHAR(255),
  PERMIT_STATUS VARCHAR(255),
  HISTORICAL_RECORD VARCHAR(255),
  COMMENTS VARCHAR(255),
  FOLDERRSN INTEGER,
  WATERSHED VARCHAR(255)
);
